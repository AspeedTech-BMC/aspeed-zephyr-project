"""Bring the module copies of vendor Zephyr drivers up to a newer vendor commit.

Each line of vendor_map.txt pairs a module file with its source in the vendor
Zephyr tree. vendor_base holds the vendor commit the module copies currently
match. For every pair this runs a three-way merge (git merge-file): the module
file keeps its own edits (include paths, upstream API names) and takes the
vendor changes between vendor_base and the target commit. New files are copied
with the include and API rewrites below. Each module header copied from the
vendor include/zephyr tree also gets a forwarding header at its vendor path.
vendor_base is updated when no conflict is left.

Usage: sync_vendor.py <vendor zephyr repo> [target commit, default HEAD]
                      [--add <module path>=<vendor path> ...]
                      [--dry-run] [--set-base]

--dry-run reports what a sync would update or leave in conflict. After
conflicts are resolved by hand, --set-base records the target as vendor_base.
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
# The mainline module root, which the paths in vendor_map.txt are relative to.
MODULE = HERE.parent

# Vendor include paths and their module equivalents, applied to newly added files.
INCLUDE_REWRITES = [
    ("<zephyr/drivers/misc/aspeed/", "<aspeed/"),
    ("<zephyr/drivers/cptra.h>", "<aspeed/cptra.h>"),
    ("<zephyr/crypto/ecdsa.h>", "<aspeed/ecdsa.h>"),
    ("<zephyr/crypto/ecdsa_structs.h>", "<aspeed/ecdsa_structs.h>"),
    ("<zephyr/crypto/lms.h>", "<aspeed/lms.h>"),
    ("<zephyr/crypto/lms_structs.h>", "<aspeed/lms_structs.h>"),
]

# The vendor tree adds per-ID calls to the generic IPM API; upstream IPM has no
# such calls, so the module exposes them from the BootMCU IPM driver instead.
API_REWRITES = [
    ("ipm_register_id_callback(", "ipm_bootmcu_register_id_callback("),
    ("ipm_set_id_enabled(", "ipm_bootmcu_set_id_enabled("),
]


def git_show(repo, rev, path):
    res = subprocess.run(["git", "-C", str(repo), "show", f"{rev}:{path}"],
                         capture_output=True)
    return res.stdout if res.returncode == 0 else None


def read_map():
    pairs = []
    for line in (HERE / "vendor_map.txt").read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            mod, ven = line.split()
            pairs.append((mod, ven))
    return pairs


SHIM = """/*
 * Copyright (c) 2026 ASPEED Technology Inc.
 *
 * SPDX-License-Identifier: Apache-2.0
 *
 * Generated by mainline/scripts/sync_vendor.py: the vendor include path of
 * <{target}>, so sources written for the vendor tree build unchanged.
 */

#include <{target}>
"""


def write_shims(pairs):
    """Give each module header copied from the vendor include/ tree its vendor path."""
    for mod, ven in pairs:
        if mod.startswith("include/aspeed/") and ven.startswith("include/zephyr/"):
            shim = MODULE / ven
            shim.parent.mkdir(parents=True, exist_ok=True)
            shim.write_text(SHIM.format(target=mod[len("include/"):]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("vendor")
    ap.add_argument("target", nargs="?", default="HEAD")
    ap.add_argument("--add", action="append", default=[],
                    help="<module path>=<vendor path> to copy and add to the map")
    ap.add_argument("--dry-run", action="store_true",
                    help="report what would be updated or conflict, write nothing")
    ap.add_argument("--set-base", action="store_true",
                    help="record target as vendor_base after conflicts were resolved by hand")
    args = ap.parse_args()

    vendor = Path(args.vendor)
    base = (HERE / "vendor_base").read_text().split()[0]
    target = subprocess.run(["git", "-C", str(vendor), "rev-parse", args.target],
                            capture_output=True, text=True, check=True).stdout.strip()
    pairs = read_map()

    if args.set_base:
        marked = [m for m, _ in pairs
                  if (MODULE / m).exists() and "\n<<<<<<< " in (MODULE / m).read_text()]
        if marked:
            sys.exit("conflict markers left in: " + " ".join(marked))
        write_shims(pairs)
        (HERE / "vendor_base").write_text(target + "\n")
        print(f"vendor_base -> {target}")
        return 0

    changed, conflicts, gone = [], [], []

    for mod, ven in pairs:
        old = git_show(vendor, base, ven)
        new = git_show(vendor, target, ven)
        if new is None:
            gone.append(mod)
            continue
        if old == new:
            continue
        with tempfile.TemporaryDirectory() as tmp:
            b = Path(tmp, "base")
            t = Path(tmp, "theirs")
            b.write_bytes(old or b"")
            t.write_bytes(new)
            cmd = ["git", "merge-file", "-L", "module", "-L", f"vendor {base[:12]}",
                   "-L", f"vendor {target[:12]}"]
            if args.dry_run:
                cmd.append("-p")
            res = subprocess.run(cmd + [str(MODULE / mod), str(b), str(t)],
                                 stdout=subprocess.DEVNULL if args.dry_run else None)
        (conflicts if res.returncode != 0 else changed).append(mod)

    if args.dry_run:
        for mod in changed:
            print(f"would update   {mod}")
        for mod in conflicts:
            print(f"would CONFLICT {mod}")
        for mod in gone:
            print(f"REMOVED        {mod} (no longer in vendor tree)")
        print(f"{len(changed)} to update, {len(conflicts)} conflict(s), {len(gone)} removed "
              f"({base[:12]} -> {target[:12]})")
        return 0

    for spec in args.add:
        mod, ven = spec.split("=", 1)
        data = git_show(vendor, target, ven)
        if data is None:
            sys.exit(f"{ven} not found at {target[:12]}")
        text = data.decode()
        for a, b in INCLUDE_REWRITES:
            text = text.replace(a, b)
        if any(a in text for a, _ in API_REWRITES):
            for a, b in API_REWRITES:
                text = text.replace(a, b)
            text = text.replace("#include <zephyr/drivers/ipm.h>\n",
                                "#include <zephyr/drivers/ipm.h>\n#include <aspeed/ipm_bootmcu.h>\n")
        dst = MODULE / mod
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(text)
        pairs.append((mod, ven))
        changed.append(mod + " (added)")

    if args.add:
        lines = ["# <module path> <vendor zephyr path>"]
        lines += [f"{m} {v}" for m, v in sorted(set(pairs))]
        (HERE / "vendor_map.txt").write_text("\n".join(lines) + "\n")

    write_shims(pairs)

    for mod in changed:
        print(f"updated   {mod}")
    for mod in conflicts:
        print(f"CONFLICT  {mod}")
    for mod in gone:
        print(f"REMOVED   {mod} (no longer in vendor tree)")
    if conflicts:
        print(f"{len(conflicts)} conflict(s); resolve them, then run again with --set-base")
        return 1
    (HERE / "vendor_base").write_text(target + "\n")
    print(f"vendor_base -> {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
